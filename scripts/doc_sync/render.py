"""Deterministic markdown rendering. Every emitted cell is passed through redact()."""
from __future__ import annotations

import re
from typing import Iterable

from .extract import Mode, Route, Service

NOTICE = "<!-- Generated by scripts/doc_sync from source code. Do not edit by hand; run `python -m scripts.doc_sync --write`. -->"

_SECRET_PATTERNS = [
    re.compile(r"\bsk-[A-Za-z0-9_\-]{8,}"),
    re.compile(r"\bgsk_[A-Za-z0-9]{8,}"),
    re.compile(r"\bAIza[0-9A-Za-z_\-]{10,}"),
    re.compile(r"\bATATT[0-9A-Za-z_\-=]{10,}"),
    re.compile(r"\bgh[pousr]_[A-Za-z0-9]{10,}"),
    re.compile(r"\bBearer\s+[A-Za-z0-9._\-]{8,}"),
]
_ASSIGNMENT = re.compile(r"(?i)\b([A-Z0-9_]*(?:KEY|TOKEN|SECRET|PASSWORD)[A-Z0-9_]*)\s*[=:]\s*\S+")


def redact(text: str) -> str:
    for pattern in _SECRET_PATTERNS:
        text = pattern.sub("[REDACTED]", text)
    return _ASSIGNMENT.sub(lambda m: f"{m.group(1)}=[REDACTED]", text)


def _cell(value: str) -> str:
    return redact(value).replace("|", "\\|").replace("\r", " ").replace("\n", " ").strip()


def _table(header: list[str], rows: Iterable[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _block(table: str) -> str:
    return f"\n{NOTICE}\n\n{table}\n"


def render_routes(routes: list[Route]) -> str:
    rows = [[r.method, f"`{r.path}`", f"`{r.handler}()`", r.summary, f"`{r.source}`"] for r in routes]
    return _block(_table(["Method", "Path", "Handler", "Summary", "Source"], rows))


def render_services(services: list[Service]) -> str:
    rows = [[f"`{s.module}`", s.purpose, ", ".join(f"`{n}`" for n in s.symbols) or "None"] for s in services]
    return _block(_table(["Module", "Purpose", "Public symbols"], rows))


def render_modes(modes: list[Mode]) -> str:
    rows = [[f"`{m.id}`", m.label, m.description] for m in modes]
    return _block(_table(["Mode ID", "Label", "Description"], rows))
